def crc8(data):
    c=0
    for b in data:c=CRC_TABLE[(c^b)&0xff]
    return c
@dataclass(frozen=True)
class Point: angle:float; distance:float; confidence:int
class Parser:
    def __init__(self):self.buf=bytearray();self.crc_bad=0;self.discarded=0
    def feed(self,data):
        self.buf.extend(data);out=[]
        while len(self.buf)>=2:
            while len(self.buf)>=2 and self.buf[:2]!=b'\x54\x2c':del self.buf[0];self.discarded+=1
            if len(self.buf)<FRAME_LEN:break
            raw=bytes(self.buf[:FRAME_LEN])
            if crc8(raw[:-1])!=raw[-1]:del self.buf[0];self.crc_bad+=1;continue
            u16=lambda i:raw[i]|raw[i+1]<<8
            speed,start,end,stamp=u16(2),u16(4)/100,u16(42)/100,u16(44);span=(end-start)%360
            pts=[Point((start+span*i/11)%360,u16(6+i*3)/1000,raw[8+i*3]) for i in range(12)]
            out.append((speed,start,end,stamp,pts));del self.buf[:FRAME_LEN]
        return out
def main():
    ap=argparse.ArgumentParser(description='LD14 UART6 独立验证')
    ap.add_argument('--port',default='/dev/ttyS6');ap.add_argument('--baud',type=int,default=115200)
    ap.add_argument('--csv',default='ld14_capture.csv');ap.add_argument('--seconds',type=float,default=0,help='0表示持续到Ctrl+C')
    ap.add_argument('--min-confidence',type=int,default=0);args=ap.parse_args()
    try:
        import serial
    except ImportError as exc:
        raise SystemExit('缺少 pyserial，请在项目虚拟环境执行: python -m pip install pyserial') from exc
    parser=Parser();running=True;frames=bytes_in=0;t0=last=time.monotonic();last_frames=last_bytes=0
    def stop(*_):
        nonlocal running;running=False
    signal.signal(signal.SIGINT,stop);signal.signal(signal.SIGTERM,stop)
    with serial.Serial(args.port,args.baud,timeout=.1) as port,open(args.csv,'w',newline='',encoding='utf-8-sig') as fh:
        writer=csv.writer(fh);writer.writerow(['host_time','frame','lidar_timestamp_ms','speed_dps','start_deg','end_deg','angle_deg','distance_m','confidence'])
        print(f'读取 {args.port} @ {args.baud}，CSV: {args.csv}，Ctrl+C结束')
        while running and (args.seconds<=0 or time.monotonic()-t0<args.seconds):
            data=port.read(1024);bytes_in+=len(data)
            for speed,start,end,stamp,points in parser.feed(data):
                frames+=1;valid=[p for p in points if p.distance>0 and p.confidence>=args.min_confidence]
                for p in points:writer.writerow([f'{time.time():.3f}',frames,stamp,speed,f'{start:.2f}',f'{end:.2f}',f'{p.angle:.2f}',f'{p.distance:.3f}',p.confidence])
                if valid:
                    near=min(valid,key=lambda p:p.distance)
                    near_text=f'{near.distance:.3f}m @ {near.angle:.1f}deg conf={near.confidence}'
                else:near_text='--'
            now=time.monotonic()
            if now-last>=1:
                dt=now-last;fps=(frames-last_frames)/dt;bps=(bytes_in-last_bytes)/dt
                print(f'frames={frames} fps={fps:.1f} speed={(speed/360 if frames else 0):.2f}Hz bytes/s={bps:.0f} crc_bad={parser.crc_bad} discard={parser.discarded} nearest={near_text if frames else "--"}')
                fh.flush();last=now;last_frames=frames;last_bytes=bytes_in
    print(f'完成: frames={frames}, crc_bad={parser.crc_bad}, discarded={parser.discarded}, bytes={bytes_in}')
if __name__=='__main__':main()
